const req = (
  id: number,
  scenario_key: string,
  full_name: string,
  phone: string,
  payload: Record<string, unknown>,
  status: "new" | "processed",
  dayOffset: number,
  hh: number,
  admin_comment: string | null = null,
): RequestRow => ({
  id,
  user_id: id,
  scenario_key,
  payload,
  full_name,
  phone,
  status,
  admin_comment,
  processed_at: status === "processed" ? TS(dayOffset, hh + 1) : null,
  processed_by: null,
  created_at: TS(dayOffset, hh),
});

