// «сегодня» для демо фиксируем, чтобы вид был стабильным (2026-09-22)
const D = (offset: number) => {
  const d = new Date(2026, 8, 22 + offset); // локальная дата, месяц 0-индексный
  const p = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
};
const TS = (day: number, hh: number, mm = 0) =>
  new Date(2026, 8, 22 + day, hh, mm).toISOString();

